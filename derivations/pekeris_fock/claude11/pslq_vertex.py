import mpmath as mp
mp.mp.dps = 50
vals = {
 'A3': '-0.0925600612116326301461641872929311187211379519080074458',
 'A4': '-0.01028083791780141522795259479153765743261843693754253802',
 'B4': '-0.02142330272329080516026101409699792868415487258468436057',
 'C1': '0.04837080730775888705488027555520225278343997618889356525',
 'C2': '-0.1378956029975717004721377714483530780297683409873093147',
 'C3e1': '0.303407220298144850775314748249455281583968036965498501',
 'p30': '0.1514856263105115905129012174683352053282076135125262339',
}
s2 = mp.sqrt(2); pi = mp.pi; L = mp.log(1 + s2); l2 = mp.log(2)
w = mp.gamma(0.25)**2 / (2 * mp.sqrt(2 * pi))   # lemniscate constant
base = [('1', 1), ('s2', s2), ('pi', pi), ('pi s2', pi * s2), ('L', L), ('s2 L', s2 * L), ('l2', l2), ('s2 l2', s2 * l2), ('1/pi', 1 / pi), ('s2/pi', s2 / pi), ('L/pi', L / pi), ('s2L/pi', s2 * L / pi)]
ell = [('w', w), ('s2 w', s2 * w), ('pi/w', pi / w), ('s2 pi/w', s2 * pi / w)]
for k, v in vals.items():
    x = mp.mpf(v)
    for nm, B in (('Tate-ish', base), ('with lemniscate', base + ell)):
        r = mp.pslq([x] + [b for _, b in B], maxcoeff=10**6, maxsteps=10**6)
        print(k, nm, r if r is None else ' + '.join(f'{c}*{n}' for c, (n, _) in zip(r[1:], B) if c) + f'  (x coeff {r[0]})')
