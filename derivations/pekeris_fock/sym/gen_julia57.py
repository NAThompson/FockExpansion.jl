"""Emit the 57-term fixed-eps Pekeris recurrence (general E) for Julia: coefficient = c0 + E*c1, polynomial in l,m,n,eps (Z=2, lambda=1)."""
import json
import sympy as sp
l, m, n, eps, E, Z, lam = sp.symbols('l m n epsilon E Z lam')
rec = json.load(open('recurrence.json'))['P_general']
loc = {'epsilon': eps, 'Z': Z, 'lam': lam, 'l': l, 'm': m, 'n': n, 'E': E}
lines = ['# generated by sym/gen_julia57.py: sum_off (c0 + E c1)(l,m,n) A(l+off) = 0, Z=2, lambda=1', 'const PEKERIS57 = [']
for k, s in sorted(rec.items()):
    ex = sp.expand(sp.sympify(s.replace('lambda', 'lam'), locals=loc).subs({Z: 2, lam: 1}))
    c1 = sp.expand(ex.coeff(E, 1)); c0 = sp.expand(ex - c1 * E)
    assert E not in c0.free_symbols
    lines.append(f'    ({k}, (l, m, n, epsilon) -> {sp.julia_code(c0)}, (l, m, n, epsilon) -> {sp.julia_code(c1)}),')
lines.append(']')
open('../claude5/generated57.jl', 'w').write('\n'.join(lines) + '\n')
print(len(rec))
