"""Emit Julia code: the 33-term recurrence (eps^2=-E) and the operator P (general E)."""
import json
import sympy as sp
from pekeris_operator import u, v, w, eps, E, Z, lam
from recurrence import op_scaled

l, m, n = sp.symbols('l m n')
rec = json.load(open('recurrence.json'))['P']
loc = {'epsilon': eps, 'Z': Z, 'lam': lam, 'l': l, 'm': m, 'n': n}
lines = ['# generated by sym/gen_julia.py — do not edit',
         '# 33-term Pekeris recurrence: sum_off coeff(l,m,n) * A(l+off) = 0 (eps^2 = -E)',
         'const PEKERIS33 = [']
for k, s in sorted(json.load(open('recurrence.json'))['P'].items()):
    ex = sp.expand(sp.sympify(s.replace('lambda', 'lam'), locals=loc) / eps)  # linear in eps
    a0 = sp.expand(ex.subs(eps, 0))
    a1 = sp.expand(ex.coeff(eps, 1))
    assert sp.expand(ex - a0 - a1 * eps) == 0
    lines.append(f'    ({k}, (l, m, n, Z, lam) -> {sp.julia_code(a0)}, (l, m, n, Z, lam) -> {sp.julia_code(a1)}),')
lines.append(']')
lines.append('# operator P = sum coef(u,v,w) d^a_u d^b_v d^c_w ; entries (deriv, mono, (eps,E,Z,lam) -> coefficient)')
lines.append('const PEKERIS_OP = [')
for der, coef in sorted(op_scaled().items()):
    poly = sp.Poly(coef, u, v, w)
    for mono, c in poly.terms():
        lines.append(f'    ({der}, {mono}, (eps, E, Z, lam) -> {sp.julia_code(sp.expand(c))}),')
lines.append(']')
open('../julia/generated.jl', 'w').write('\n'.join(lines) + '\n')
print('ok')
